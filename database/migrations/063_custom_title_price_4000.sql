-- =============================================================================
-- 063_custom_title_price_4000.sql — цена персонального титула 6000 → 4000
-- (Bot 2.0, Stage 5; правка к ECONOMY_V4, миграция 062)
--
-- ЗАЧЕМ. Решение пользователя 2026-07-31: 6000 после ребаланса недостижимы на практике.
-- Проверка по ECONOMY_V4_PROPOSAL §§5-6: у профиля 6 ежедневок доход 832 за период, после
-- каталога (460) и корма (70) остаётся 302. 6000 — это 20 периодов (около 9 месяцев) при
-- обычных тратах; 4000 — 13 периодов, а при осознанном отказе от сезонного каталога около
-- пяти. Цель становится долгой, но реальной.
--
-- ПОБОЧНЫЙ ЭФФЕКТ, ЗАФИКСИРОВАН СОЗНАТЕЛЬНО. Персональный титул перестаёт быть самым дорогим
-- товаром: легендарные рамки стоят 4400. Если позиция «титул — вершина витрины» важна,
-- легендарные рамки следует опустить до 3600 отдельным решением; сейчас это не делается.
--
-- ГРАНИЦЫ. Меняется ровно одна цена в shop_items. Функции, ledger, балансы, уже одобренные
-- титулы и очередь модерации не трогаются: submit_custom_title читает цену из shop_items.
-- Клиентский текст модалки правится вместе с этой миграцией (цена там зашита в разметке).
-- =============================================================================

begin;

do $preflight$
declare v_price integer;
begin
  select price into v_price from public.shop_items where item_code = 'title_custom';
  if v_price is null then
    raise exception '063 ABORT: товар title_custom отсутствует';
  end if;
  if v_price <> 6000 then
    raise exception '063 ABORT: ожидалась цена 6000 после миграции 062, найдена %', v_price;
  end if;
end
$preflight$;

update public.shop_items set price = 4000 where item_code = 'title_custom';

do $postflight$
begin
  if (select price from public.shop_items where item_code = 'title_custom') <> 4000 then
    raise exception '063 ABORT: цена не применилась';
  end if;
end
$postflight$;

commit;

